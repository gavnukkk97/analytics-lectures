# -*- coding: utf-8 -*-
"""Практика 1.1 — Три теста вопроса и стоимость анализа (кейс «ЕдаДома»).

Что делаем:
1) Чек-лист «вопрос бизнеса → постановка»: метрика + сравнение + горизонт + решение.
2) Считаем, когда анализ оправдан: цена анализа против цены ошибки.

Запуск: python3 course/modules/M1/practice/practice_1_1.py
"""
from __future__ import annotations

# %% [markdown]
# Шаг 1. Прогоняем «сырые» вопросы бизнеса через три теста.

# %%
questions = [
    # (вопрос, метрика, сравнение, горизонт, решение, тест_решения, измеримо, стоит_ли)
    ("Блогеры же работают?",
     "CAC и LTV90 когорт по каналам",
     "блогеры vs контекст (когорты одного возраста)",
     "90 дней",
     "перераспределение бюджета",
     True, True, True),
    ("Сколько нам пользователей в Новосибирске?",
     "размер аудитории города",
     "—",
     "—",
     "нет решения, зависящего от числа",
     False, True, True),
    ("Насколько мы классные?",
     "—",
     "—",
     "—",
     "нет действия",
     False, False, False),
    ("Надо ли продлевать бесплатную доставку?",
     "инкрементальная маржа против контрфакта",
     "периоды/гео с акцией и без",
     "60–90 дней",
     "продлить/отменить/поменять порог",
     True, True, True),
]

print(f"{'Вопрос':38} | {'решение?':9} | {'измеримо?':9} | {'стоит?':7} | вердикт")
print("-" * 100)
for q, m, c, h, d, t1, t2, t3 in questions:
    verdict = "БЕРЁМ В РАБОТУ" if (t1 and t2 and t3) else "вернуть на переформулировку"
    print(f"{q:38} | {str(t1):9} | {str(t2):9} | {str(t3):7} | {verdict}")
    if t1 and t2 and t3:
        print(f"   → постановка: {m} | {c} | горизонт {h} | решение: {d}")

# %% [markdown]
# Шаг 2. Цена анализа против цены ошибки.
# Анализ оправдан, если стоимость анализа < вероятность_ошибки × цена_ошибки.

# %%
cases = [
    # (решение, цена_ошибки ₽, вероятность ошибки «на глаз», стоимость анализа ₽)
    ("Перекинуть 5 млн бюджета блогеры↔контекст", 2_000_000, 0.30, 150_000),
    ("Продлить акцию доставки на месяц", 800_000, 0.40, 300_000),
    ("Поменять цвет кнопки в рассылке", 30_000, 0.50, 120_000),
]
print(f"\n{'Решение':45} | цена ошибки | P(ошибки) | анализ оправдан?")
print("-" * 100)
for name, cost_err, p_err, cost_an in cases:
    ok = cost_an < p_err * cost_err
    print(f"{name:45} | {cost_err:>10,} | {p_err:>9.0%} | "
          f"{'ДА' if ok else 'НЕТ — дешевле решить без анализа'}"
          f" (ожидаемая потеря {p_err * cost_err:,.0f} ₽ vs анализ {cost_an:,} ₽)")

print("""
Вывод: дорогие решения при высокой неопределённости окупают даже дорогой анализ
(эксперименты — модуль М5); дешёвые решения с низкой ценой ошибки можно
принимать без анализа — и это тоже аналитическое решение.
""")
