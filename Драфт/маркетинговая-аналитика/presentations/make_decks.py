"""Генератор презентаций курса «Маркетинговая аналитика» (М1–М2).

Стиль: лекции Кирилла Садчикова — открывашка «как прошла неделя?», один тезис
на слайд, большие числа, минимум текста, подводные камни и шпаргалка в конце.
Запуск: python3 presentations/make_decks.py  → presentations/Урок *.pptx
"""
from __future__ import annotations
from pathlib import Path
from pptx import Presentation
from pptx.util import Inches, Pt
from pptx.dml.color import RGBColor
from pptx.enum.text import PP_ALIGN

BG, PRIMARY, ACCENT, MUTED, LIGHT = "FFFFFF", "1F2A44", "E8590C", "6B7280", "F4F5F7"
FONT = "Arial"
W, H, M = 13.33, 7.5, 0.6
OUT = Path(__file__).resolve().parent

def _tf(slide, x, y, w, h, text, size=20, color='333333', bold=False, align=PP_ALIGN.LEFT, font=FONT):
    box = slide.shapes.add_textbox(Inches(x), Inches(y), Inches(w), Inches(h))
    tf = box.text_frame; tf.word_wrap = True
    lines = text if isinstance(text, list) else [text]
    for i, ln in enumerate(lines):
        p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
        p.alignment = align
        if isinstance(ln, tuple):  # (text, size, color, bold)
            t, sz, c, b = ln
        else:
            t, sz, c, b = ln, size, color, bold
        r = p.add_run(); r.text = t
        r.font.name = font; r.font.size = Pt(sz); r.font.bold = b
        r.font.color.rgb = RGBColor.from_string(c)
    return box

def new_prs():
    prs = Presentation()
    prs.slide_width = Inches(W); prs.slide_height = Inches(H)
    return prs

def add_slide(prs, dark=False):
    s = prs.slides.add_slide(prs.slide_layouts[6])
    s.background.fill.solid()
    s.background.fill.fore_color.rgb = RGBColor.from_string(PRIMARY if dark else BG)
    return s

def title_slide(prs, num, title, subtitle):
    s = add_slide(prs, dark=True)
    _tf(s, M, 2.0, W - 2 * M, 0.5, [f"МОДУЛЬ {num.split('.')[0]} · УРОК {num}"], 16, "8FA3C4", bold=True)
    _tf(s, M, 2.6, W - 2 * M, 2.0, [title], 44, "FFFFFF", bold=True)
    _tf(s, M, 5.9, W - 2 * M, 0.9, [subtitle, "Кирилл Садчиков · маркетинговая аналитика"], 16, "AEB9CE")
    return prs

def opener_slide(prs, questions):
    s = add_slide(prs)
    _tf(s, M, 0.5, W - 2 * M, 0.7, ["Как прошла неделя?"], 32, PRIMARY, bold=True)
    rows = [(q, 22, "333333", False) for q in questions]
    _tf(s, M, 1.8, W - 2 * M, 4.6, rows + [("", 10, MUTED, False)] +
        [("Что запомнили с прошлого урока? Что хотели бы проверить у себя на работе?", 18, MUTED, False)],
        22, "333333")
    return prs

def statement_slide(prs, big, small=None):
    s = add_slide(prs)
    _tf(s, M, 2.2, W - 2 * M, 2.6, [big], 34, PRIMARY, bold=True)
    if small:
        _tf(s, M, 5.0, W - 2 * M, 1.6, [small], 18, MUTED)
    return prs

def bigstat_slide(prs, number, label, note=None):
    s = add_slide(prs)
    _tf(s, M, 1.7, 5.2, 2.6, [number], 88, ACCENT, bold=True)
    _tf(s, M, 4.3, 5.4, 1.6, [label], 24, PRIMARY, bold=True)
    if note:
        _tf(s, 6.4, 1.9, 6.3, 4.4, [(n, 17, "333333", False) for n in note])
    return prs

def bullets_slide(prs, title, bullets, focal=None):
    s = add_slide(prs)
    _tf(s, M, 0.5, W - 2 * M, 0.8, [title], 30, PRIMARY, bold=True)
    if focal:  # большое слово/число слева как визуальный якорь
        _tf(s, M, 1.9, 3.6, 3.6, [(focal[0], 54, ACCENT, True), (focal[1], 15, MUTED, False)], align=PP_ALIGN.CENTER)
        x, w = 4.9, W - 2 * M - 4.3
    else:
        x, w = M, W - 2 * M
    rows = []
    for b in bullets:
        rows.append((b, 20, "333333", False)); rows.append(("", 9, "333333", False))
    _tf(s, x, 1.9, w, 4.8, rows)
    return prs

def table_slide(prs, title, headers, rows):
    s = add_slide(prs)
    _tf(s, M, 0.5, W - 2 * M, 0.8, [title], 30, PRIMARY, bold=True)
    shp = s.shapes.add_table(len(rows) + 1, len(headers), Inches(M), Inches(1.7),
                             Inches(W - 2 * M), Inches(0.5 + 0.55 * (len(rows) + 1)))
    tbl = shp.table
    for j, htxt in enumerate(headers):
        c = tbl.cell(0, j); c.text = htxt
        p = c.text_frame.paragraphs[0]; p.runs[0].font.bold = True
        p.runs[0].font.size = Pt(15); p.runs[0].font.color.rgb = RGBColor.from_string("FFFFFF")
        c.fill.solid(); c.fill.fore_color.rgb = RGBColor.from_string(PRIMARY)
    for i, row in enumerate(rows, 1):
        for j, val in enumerate(row):
            c = tbl.cell(i, j); c.text = val
            p = c.text_frame.paragraphs[0]
            p.runs[0].font.size = Pt(14)
            p.runs[0].font.color.rgb = RGBColor.from_string("333333")
            c.fill.solid(); c.fill.fore_color.rgb = RGBColor.from_string(LIGHT if i % 2 else "FFFFFF")
    return prs

def closing_slide(prs, homework):
    s = add_slide(prs, dark=True)
    _tf(s, M, 1.4, W - 2 * M, 1.2, ["Что дальше"], 36, "FFFFFF", bold=True)
    rows = [(f"→ {h}", 20, "D9E1EF", False) for h in homework]
    _tf(s, M, 2.9, W - 2 * M, 3.4, rows)
    _tf(s, M, 6.6, W - 2 * M, 0.5, ["Курс «Маркетинговая аналитика» · драфт"], 13, "8FA3C4")
    return prs

def build(num, title, subtitle, opener, slides, homework):
    prs = new_prs()
    title_slide(prs, num, title, subtitle)
    if opener: opener_slide(prs, opener)
    for sl in slides:
        kind = sl[0]
        if kind == "stmt": statement_slide(prs, sl[1], sl[2] if len(sl) > 2 else None)
        elif kind == "stat": bigstat_slide(prs, sl[1], sl[2], sl[3] if len(sl) > 3 else None)
        elif kind == "bul": bullets_slide(prs, sl[1], sl[2], sl[3] if len(sl) > 3 else None)
        elif kind == "tbl": table_slide(prs, sl[1], sl[2], sl[3])
    closing_slide(prs, homework)
    path = OUT / f"Урок {num} — {slugged(title)}.pptx".replace("/", " ")
    prs.save(path)
    return path

def slugged(t):
    return t.split(" — ")[0].split(":")[0].strip()[:48]

