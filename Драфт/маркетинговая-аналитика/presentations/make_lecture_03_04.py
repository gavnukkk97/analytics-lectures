IMAGES = HERE.parent / "course" / "modules" / "M4" / "images"
SLIDE_W_IN = 20.0


def pic_slide(prs, carriers, title, img_name):
    """Слайд-картинка: заголовок-тезис + изображение по центру."""
    s = clone_slide(prs, carriers[1])
    fill_stmt(s, title)                      # заголовок; блок пояснения очищается
    img = IMAGES / img_name
    w_px, h_px = PILImage.open(img).size
    max_h, max_w = 7.35, 18.6
    scale = min(max_h / (h_px / 150.0), max_w / (w_px / 150.0))
    pic_w, pic_h = w_px / 150.0 * scale, h_px / 150.0 * scale
    s.shapes.add_picture(str(img), Inches((SLIDE_W_IN - pic_w) / 2),
                         Inches(3.15), width=Inches(pic_w), height=Inches(pic_h))
    return s


